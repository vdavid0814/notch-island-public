import AppKit
import Foundation
import Observation

/// One piece of text the user copied.
nonisolated struct ClipboardItem: Hashable, Identifiable, Sendable, Codable {
    var id = UUID()
    var text: String
    var copied: Date

    /// The first line, for a row (the whole text is what gets pasted): read up to the first line
    /// break only, and no longer than a row shows (splitting a long copy into all its lines ran on
    /// every redraw of the list).
    var preview: String {
        let start = text.drop { $0.isNewline }
        return String(start.prefix { !$0.isNewline }.prefix(Self.previewLength)).trimmingCharacters(in: .whitespaces)
    }

    static let previewLength = 300
}

/// What the user copied, newest first, for Siri's Clipboard (⌘4), as the system's Spotlight keeps
/// it: text only, the last `limit` copies, kept across launches.
///
/// The pasteboard has no change notification, so its change count is read once a second — one
/// integer from the pasteboard server, with a generous timer leeway so the wake-up rides along
/// with others — on a queue of its own (`PasteboardWatch`). Nothing else runs until the count moves. Copies an app marks as concealed or
/// transient (password managers, per nspasteboard.org) are never kept.
@Observable final class ClipboardHistory {
    private(set) var items: [ClipboardItem] = []

    static let limit = 50
    /// Longer copies are kept cut to this (a row shows one line; nobody pastes a book from here).
    static let maximumLength = 20_000
    nonisolated static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    @ObservationIgnored private let pasteboard: NSPasteboard
    @ObservationIgnored private let storeURL: URL?
    @ObservationIgnored private var watch: PasteboardWatch?
    @ObservationIgnored private var lastChangeCount: Int

    init(pasteboard: NSPasteboard = .general, storeURL: URL? = ClipboardHistory.defaultStoreURL) {
        self.pasteboard = pasteboard
        self.storeURL = storeURL
        lastChangeCount = pasteboard.changeCount
        if let storeURL, let data = try? Data(contentsOf: storeURL),
           let saved = try? JSONDecoder().decode([ClipboardItem].self, from: data) {
            items = Array(saved.prefix(Self.limit))
        }
    }

    nonisolated static var defaultStoreURL: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appendingPathComponent("NotchIsland", isDirectory: true)
            .appendingPathComponent("Clipboard.json")
    }

    /// Watches the pasteboard (Settings ▸ Siri ▸ Clipboard on) or stops, keeping what it has.
    func setWatching(_ watching: Bool) {
        if watching {
            guard watch == nil else { return }
            watch = PasteboardWatch(pasteboard: pasteboard) { [weak self] count, isFirst in
                guard let self else { return }
                // Copies made while nothing watched are not taken in (as before).
                if isFirst { self.lastChangeCount = count } else { self.check(count) }
            }
        } else {
            watch?.stop()
            watch = nil
        }
    }

    /// The items for the clipboard list (Siri's, the Clipboard widget): the pasteboard looked at again first (at most every two
    /// seconds), as nobody at the Mac it is looked at only every thirty (`PasteboardWatch`).
    func itemsForList() -> [ClipboardItem] {
        let now = CACurrentMediaTime()
        if now - lastLookRequest > 2 {
            lastLookRequest = now
            watch?.lookNow()
        }
        return items
    }

    @ObservationIgnored private var lastLookRequest: CFTimeInterval = 0

    /// Reads the pasteboard if it changed since the last look (`count`: its change count, read).
    func check(_ count: Int? = nil) {
        let count = count ?? pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes), let text = pasteboard.string(forType: .string) else { return }
        add(text)
    }

    func add(_ text: String, at date: Date = .now) {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        let text = String(text.prefix(Self.maximumLength))
        // The same text again moves up instead of appearing twice.
        items.removeAll { $0.text == text }
        items.insert(ClipboardItem(text: text, copied: date), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        save()
    }

    func remove(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items = []
        save()
    }

    /// Puts `item` on the pasteboard (and at the top of the history) without it counting as a new
    /// copy.
    func place(_ item: ClipboardItem) {
        pasteboard.clearContents()
        pasteboard.setString(item.text, forType: .string)
        lastChangeCount = pasteboard.changeCount
        add(item.text)
    }

    private func save() {
        guard let storeURL else { return }
        let items = items
        Task.detached(priority: .utility) {
            try? FileManager.default.createDirectory(at: storeURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            guard let data = try? JSONEncoder().encode(items) else { return }
            try? data.write(to: storeURL, options: [.atomic, .completeFileProtection])
        }
    }

    /// Pastes into the app that was frontmost before Siri took the keyboard: ⌘V, sent once that app
    /// is active again. Needs Accessibility (the island has it for the media keys); without it the
    /// text is only on the pasteboard, ready for the user's own ⌘V.
    nonisolated static func pasteIntoFrontApp() {
        guard AXIsProcessTrusted() else { return }
        let source = CGEventSource(stateID: .combinedSessionState)
        let v: CGKeyCode = 9
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

/// The pasteboard's change count, read on a queue of its own: the read is a message to the
/// pasteboard server that waits for its answer, and on a Mac short of memory it stood the main
/// thread still for over 2 s (App Hang in `ClipboardHistory.check`, October 13). The main thread
/// hears only of a change (`onChange`, with the first count read as `isFirst`).
///
/// At background quality of service: the look runs on the efficiency cores (on the main thread it
/// ran on a performance core), and a copy seen a moment later changes nothing.
///
/// Once a second while the Mac is being used; every five seconds once nothing has been typed or
/// clicked for a minute; every thirty once nothing has for ten (nobody at the Mac: at rest the look
/// was the app's only wake-up). A copy needs a keystroke or a click, and the clipboard list looks
/// again as it is shown (`lookNow`), so a late look is never seen.
nonisolated final class PasteboardWatch: @unchecked Sendable {
    private let queue = DispatchQueue(label: "com.davidvarga.notchisland.pasteboard", qos: .background)
    private let timer: any DispatchSourceTimer
    private let onChange: @MainActor (_ count: Int, _ isFirst: Bool) -> Void
    // Touched on `queue` only.
    private let pasteboard: NSPasteboard
    private var lastCount: Int?
    private var pace = Pace.used

    enum Pace: Equatable {
        case used, idle, away

        /// How long nothing has been typed or clicked: `idle` past a minute, `away` past ten.
        static func after(idleSeconds: TimeInterval) -> Pace {
            idleSeconds > 600 ? .away : idleSeconds > 60 ? .idle : .used
        }

        var interval: DispatchTimeInterval {
            switch self {
            case .used: .seconds(1)
            case .idle: .seconds(5)
            case .away: .seconds(30)
            }
        }

        var leeway: DispatchTimeInterval {
            switch self {
            case .used: .milliseconds(500)
            case .idle: .seconds(2)
            case .away: .seconds(10)
            }
        }
    }

    init(pasteboard: NSPasteboard, onChange: @escaping @MainActor (_ count: Int, _ isFirst: Bool) -> Void) {
        self.pasteboard = pasteboard
        self.onChange = onChange
        timer = DispatchSource.makeTimerSource(queue: queue)
        timer.schedule(deadline: .now(), repeating: pace.interval, leeway: pace.leeway)
        timer.setEventHandler { [weak self] in
            self?.look()
            self?.setPace()
        }
        timer.resume()
    }

    func stop() { timer.cancel() }

    /// A look now, between the timer's (the clipboard list is being shown).
    func lookNow() {
        queue.async { [weak self] in self?.look() }
    }

    private func look() {
        let count = pasteboard.changeCount
        guard count != lastCount else { return }
        let isFirst = lastCount == nil
        lastCount = count
        let onChange = onChange
        DispatchQueue.main.async { MainActor.assumeIsolated { onChange(count, isFirst) } }
    }

    private func setPace() {
        let idle = CGEventSource.secondsSinceLastEventType(.combinedSessionState,
                                                           eventType: CGEventType(rawValue: ~0) ?? .null)
        let next = Pace.after(idleSeconds: idle)
        guard next != pace else { return }
        pace = next
        timer.schedule(deadline: .now() + next.interval, repeating: next.interval, leeway: next.leeway)
    }
}
